#!/data/data/com.termux/files/usr/bin/bash
#
# install-termux.sh - Install the MTTL-W01 MatterBridge inside Termux (Android)
#
# This is the Termux equivalent of the project's Dockerfile + compose.yaml.
# Docker cannot run inside the Termux app (no privileged daemon), so this
# script builds and runs the same Node.js application natively instead:
#
#   Docker stage "build"  ->  npm ci && npm run build && npm prune --omit=dev
#   Docker stage "final"  ->  node dist/index.js (started via termux-services)
#   network_mode: host    ->  native ports on the device (same behavior)
#   volumes devices/matter->  persistent files under $PREFIX/var/mttl-bridge
#   restart: unless-stopped-> runit service registered with termux-services
#
# Usage (inside Termux):
#   bash termux/install-termux.sh              # install + start service
#   MTTL_NO_START=1 bash termux/install-termux.sh   # install only
#
set -euo pipefail

PREFIX="${PREFIX:-/data/data/com.termux/files/usr}"
BIN="$PREFIX/bin"

APP_DIR="$PREFIX/var/mttl-bridge/app"
DATA_DIR="$PREFIX/var/mttl-bridge/data"
LOG_DIR="$PREFIX/var/mttl-bridge/log"
SV_DIR="$PREFIX/service/mttl-bridge"

# Defaults from compose.yaml
export TCP_PORT="${TCP_PORT:-10086}"
export HTTP_PORT="${HTTP_PORT:-8086}"
export MATTER_PORT="${MATTER_PORT:-5540}"
export MTTL_GROUP_OUTLETS="${MTTL_GROUP_OUTLETS:-0}"
export MATTER_PASSCODE="${MATTER_PASSCODE:-20202021}"
export MATTER_DISCRIMINATOR="${MATTER_DISCRIMINATOR:-3840}"
export MTTL_POLL_INTERVAL_MS="${MTTL_POLL_INTERVAL_MS:-10000}"
export MTTL_RESPONSE_TIMEOUT_MS="${MTTL_RESPONSE_TIMEOUT_MS:-3000}"

log() { printf '\033[1;36m[install]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

# --- sanity check: are we really in Termux? ---------------------------------
[ -d "$PREFIX" ] || die "Termux prefix not found at $PREFIX. Run this inside the Termux app."
case "$PREFIX" in *com.termux*) : ;; *) die "This script must run inside Termux, not a generic Linux shell." ;; esac

# --- locate the source tree (mttl-w01-matterbridge next to this script) -----
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC_DIR="$SCRIPT_DIR/../mttl-w01-matterbridge"
[ -f "$SRC_DIR/package.json" ] || die "Cannot find mttl-w01-matterbridge sources at: $SRC_DIR"
SRC_DIR="$(cd "$SRC_DIR" && pwd)"

# --- 1. packages ------------------------------------------------------------
log "Installing Termux packages (nodejs-lts, git, procps)..."
if [ "$(id -u)" = "0" ]; then
  # Termux refuses to run pkg as root; use its internal fake-id mechanism.
  AM_ROOT=1 pkg install -y nodejs-lts git procps
else
  pkg install -y nodejs-lts git procps
fi

command -v node >/dev/null || die "node was not installed correctly."
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 20 ] || die "Node >= 20 required (Docker image uses Node 22), found $(node -v)."
log "Using $(node -v) ($(uname -m))"

# --- 2. copy sources --------------------------------------------------------
log "Copying sources to $APP_DIR ..."
mkdir -p "$APP_DIR" "$DATA_DIR" "$LOG_DIR"
cp -a "$SRC_DIR/package.json" "$SRC_DIR/package-lock.json" "$SRC_DIR/tsconfig.json" "$APP_DIR/"
rm -rf "$APP_DIR/src"
cp -a "$SRC_DIR/src" "$APP_DIR/src"

cd "$APP_DIR"

# --- 3. build (mirrors Dockerfile stage "build") ----------------------------
log "npm ci (this can take several minutes on a phone)..."
npm ci --no-audit --no-fund

log "Building TypeScript..."
npm run build

log "Pruning dev dependencies and trimming artifacts..."
npm prune --omit=dev
find dist -name '*.test.*' -delete
rm -rf node_modules/@matter/*/src node_modules/@matter/*/dist/cjs
find dist node_modules -type f \( -name '*.map' -o -name '*.d.ts' \) -delete

# --- 4. environment file (read by `npm start` / dist/index.js) --------------
cat > "$APP_DIR/.env" <<ENVEOF
# Generated by install-termux.sh - edit and restart the service to apply.
NODE_ENV=production
MTTL_DEVICE_REGISTRY_FILE=$DATA_DIR/devices.json
TCP_PORT=$TCP_PORT
HTTP_PORT=$HTTP_PORT
MATTER_PORT=$MATTER_PORT
MTTL_GROUP_OUTLETS=$MTTL_GROUP_OUTLETS
MATTER_PASSCODE=$MATTER_PASSCODE
MATTER_DISCRIMINATOR=$MATTER_DISCRIMINATOR
MTTL_POLL_INTERVAL_MS=$MTTL_POLL_INTERVAL_MS
MTTL_RESPONSE_TIMEOUT_MS=$MTTL_RESPONSE_TIMEOUT_MS
ENVEOF
log "Wrote $APP_DIR/.env"

# --- 5. runit service (replaces "restart: unless-stopped") ------------------
log "Registering runit service 'mttl-bridge'..."
pkg install -y runit >/dev/null 2>&1 || AM_ROOT=1 pkg install -y runit
mkdir -p "$SV_DIR"
cat > "$SV_DIR/run" <<RUNEOF
#!/data/data/com.termux/files/usr/bin/sh
exec 2>&1
cd "$APP_DIR"
# Persistent Matter fabric/state dir lives under the Termux home directory;
# index.ts stores it at \$HOME/.matter/powerstrip-bridge automatically.
exec node --env-file-if-exists=.env dist/index.js
RUNEOF
chmod 700 "$SV_DIR/run"

# Persist env overrides across reboots for the service
{
  echo "# exported for the mttl-bridge runit service"
  grep -E '^(TCP_PORT|HTTP_PORT|MATTER_PORT|MTTL_|MATTER_)' "$APP_DIR/.env" | sed 's/^/export /'
} > "$PREFIX/var/mttl-bridge/env.sh" 2>/dev/null || true

if command -v sv >/dev/null 2>&1; then
  if [ "${MTTL_NO_START:-0}" = "1" ]; then
    log "MTTL_NO_START=1 given - service not started."
  else
    sv up mttl-bridge >/dev/null 2>&1 || true
    sleep 2
    sv status mttl-bridge || true
  fi
else
  log "WARNING: 'sv' not found; start manually with: cd $APP_DIR && npm start"
fi

# --- 6. summary --------------------------------------------------------------
LAN_IP="$(ip route get 8.8.8.8 2>/dev/null | sed -n 's/.*src \([0-9.]*\).*/\1/p' | head -1 || true)"
[ -n "$LAN_IP" ] || LAN_IP="{PHONE_IP}"

cat <<SUMMARY

============================================================
 MTTL-W01 MatterBridge installed in Termux
============================================================
 App dir : $APP_DIR
 Data    : $DATA_DIR/devices.json
 Logs    : $LOG_DIR/console.log  (tail -f "\$PREFIX/var/mttl-bridge/log/console.log")
 Ports   : HTTP $HTTP_PORT | TCP $TCP_PORT | Matter $MATTER_PORT

 Dashboard: http://$LAN_IP:$HTTP_PORT
 In Termux itself: http://127.0.0.1:$HTTP_PORT

 Service commands:
   sv status mttl-bridge      # check
   sv restart mttl-bridge     # after editing .env
   sv down mttl-bridge        # stop

 IMPORTANT (Android limitations):
   1. Termux has no Docker; this script runs the same app natively.
   2. Keep the phone plugged in and do NOT force-stop Termux.
      Enable battery optimization exemption for Termux if needed.
   3. Android may kill background processes when the screen is off.
      For a reliable always-on bridge a Raspberry Pi/NAS is preferred.
   4. The power strip must reach this phone at $LAN_IP:$TCP_PORT -
      make sure the router does not isolate clients (AP isolation off).
============================================================
SUMMARY
